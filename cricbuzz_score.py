from playwright.sync_api import sync_playwright, TimeoutError as PlaywrightTimeoutError

URL = "https://www.cricbuzz.com/cricket-match/live-scores"
SCREENSHOT = "score.png"

with sync_playwright() as p:

    # Headed mode - use this first so you can watch it.
    browser = p.chromium.launch(headless=False)

    page = browser.new_page(
        viewport={"width": 1280, "height": 900}
    )

    try:
        print("Opening Cricbuzz...")

        page.goto(
            URL,
            wait_until="domcontentloaded",
            timeout=30000
        )

        print("Waiting for live match...")

        # Locator generated by Playwright Codegen
        match = page.get_by_role(
            "link",
            name="Irani Cup • Srinagar, Sher-i-"
        )

        # Wait for the match card to appear
        match.wait_for(
            state="visible",
            timeout=15000
        )

        # Get the text inside the match card
        match_text = match.inner_text().strip()

        print()
        print("Live match:")
        print("-" * 40)
        print(match_text)
        print("-" * 40)

        # Save screenshot
        page.screenshot(
            path=SCREENSHOT,
            full_page=True
        )

        print()
        print("saved score.png")

    except PlaywrightTimeoutError:
        print()
        print("No live match appeared within 15 seconds.")
        print("There may be no live match currently.")

        page.screenshot(
            path=SCREENSHOT,
            full_page=True
        )

        print("saved score.png")

    except Exception as e:
        print()
        print(f"Error: {e}")

    finally:
        browser.close()
